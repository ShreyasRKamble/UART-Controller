`timescale 1ns/1ps

module uart_reg_interface (

    // ============================================================
    // CLOCK / RESET
    // ============================================================

    input  logic       clk,
    input  logic       rst_n,

    // ============================================================
    // HOST / CPU INTERFACE
    // ============================================================

    input  logic [2:0] addr,
    input logic       wr_en,
    input logic       rd_en,
    input logic [7:0] wr_data,

    output logic [7:0] rd_data,

    // ============================================================
    // STATUS REGISTERS
    // ============================================================

    input  logic [7:0] lsr,
    input logic [7:0] mcr,
    input logic [7:0] msr,
    input logic [7:0] scr,

    // ============================================================
    // CONTROL REGISTERS
    // ============================================================

    input logic [7:0] lcr,
    input logic [7:0] fcr,

    // ============================================================
    // DIVISOR REGISTERS
    // ============================================================

    input logic [7:0] dll,
    input logic [7:0] dlm,

    // ============================================================
    // RX DATA
    // ============================================================

    input logic [7:0] rx_data,
    input logic       rx_data_valid,

    // ============================================================
    // TX CONTROL
    // ============================================================

    output logic       tx_write,
    output logic [7:0] tx_data,

    // ============================================================
    // RX CONTROL
    // ============================================================

    output logic       rx_read,

    // ============================================================
    // REGISTER WRITE ENABLES
    // ============================================================

    output logic       lcr_wr_en,
    output logic       fcr_wr_en,

    output logic       dll_wr_en,
    output logic       dlm_wr_en,

    output logic       mcr_wr_en,
    output logic       scr_wr_en

);


    // ============================================================
    // DLAB
    //
    // LCR[7] = 1
    //
    // 0x00 -> DLL
    // 0x01 -> DLM
    //
    // LCR[7] = 0
    //
    // 0x00 -> RBR / THR
    // 0x01 -> IER
    // ============================================================

    logic dlab;

    assign dlab = lcr[7];


    // ============================================================
    // WRITE DECODE
    // ============================================================

    always_comb begin

        // --------------------------------------------------------
        // DEFAULT VALUES
        // --------------------------------------------------------

        tx_write  = 1'b0;
        tx_data   = wr_data;

        rx_read   = 1'b0;

        lcr_wr_en = 1'b0;
        fcr_wr_en = 1'b0;

        dll_wr_en = 1'b0;
        dlm_wr_en = 1'b0;

        mcr_wr_en = 1'b0;
        scr_wr_en = 1'b0;


        // --------------------------------------------------------
        // WRITE ACCESS
        // --------------------------------------------------------

        if (wr_en) begin

            case (addr)

                // =================================================
                // 0x00
                // =================================================

                3'h0: begin

                    if (dlab) begin

                        // DLL
                        dll_wr_en = 1'b1;

                    end
                    else begin

                        // THR
                        tx_write = 1'b1;

                    end

                end


                // =================================================
                // 0x01
                // =================================================

                3'h1: begin

                    if (dlab) begin

                        // DLM
                        dlm_wr_en = 1'b1;

                    end
                    else begin

                        // IER
                        // Interrupt functionality skipped.

                    end

                end


                // =================================================
                // 0x02
                // =================================================

                3'h2: begin

                    // FCR
                    fcr_wr_en = 1'b1;

                end


                // =================================================
                // 0x03
                // =================================================

                3'h3: begin

                    // LCR
                    lcr_wr_en = 1'b1;

                end


                // =================================================
                // 0x04
                // =================================================

                3'h4: begin

                    // MCR
                    mcr_wr_en = 1'b1;

                end


                // =================================================
                // 0x05
                // =================================================

                3'h5: begin

                    // LSR is read-only.

                end


                // =================================================
                // 0x06
                // =================================================

                3'h6: begin

                    // MSR is read-only in our design.

                end


                // =================================================
                // 0x07
                // =================================================

                3'h7: begin

                    // SCR
                    scr_wr_en = 1'b1;

                end


                // =================================================
                // DEFAULT
                // =================================================

                default: begin

                    // No operation.

                end

            endcase

        end


        // ========================================================
        // RX READ
        //
        // Reading address 0x00 with DLAB = 0
        // accesses RBR and therefore requests an RX FIFO read.
        // ========================================================

        if (rd_en && !dlab && (addr == 3'h0)) begin

            rx_read = 1'b1;

        end

    end


    // ============================================================
    // READ DECODE
    // ============================================================

    always_comb begin

        // Default
        rd_data = 8'h00;


        if (rd_en) begin

            case (addr)

                // =================================================
                // 0x00
                // =================================================

                3'h0: begin

                    if (dlab) begin

                        // DLL
                        rd_data = dll;

                    end
                    else begin

                        // RBR
                        rd_data = rx_data;

                    end

                end


                // =================================================
                // 0x01
                // =================================================

                3'h1: begin

                    if (dlab) begin

                        // DLM
                        rd_data = dlm;

                    end
                    else begin

                        // IER
                        // Interrupt functionality skipped.
                        rd_data = 8'h00;

                    end

                end


                // =================================================
                // 0x02
                // =================================================

                3'h2: begin

                    // IIR
                    // Interrupt functionality skipped.
                    rd_data = 8'h00;

                end


                // =================================================
                // 0x03
                // =================================================

                3'h3: begin

                    // LCR
                    rd_data = lcr;

                end


                // =================================================
                // 0x04
                // =================================================

                3'h4: begin

                    // MCR
                    rd_data = mcr;

                end


                // =================================================
                // 0x05
                // =================================================

                3'h5: begin

                    // LSR
                    rd_data = lsr;

                end


                // =================================================
                // 0x06
                // =================================================

                3'h6: begin

                    // MSR
                    rd_data = msr;

                end


                // =================================================
                // 0x07
                // =================================================

                3'h7: begin

                    // SCR
                    rd_data = scr;

                end


                // =================================================
                // DEFAULT
                // =================================================

                default: begin

                    rd_data = 8'h00;

                end

            endcase

        end

    end

endmodule